import {readFileSync,writeFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
const pubkey=process.env.SOMBRA_UPDATER_PUBLIC_KEY?.trim();
const endpoint=process.env.SOMBRA_UPDATER_ENDPOINT?.trim();
if(!pubkey||!endpoint||!process.env.TAURI_SIGNING_PRIVATE_KEY)throw Error('Set SOMBRA_UPDATER_PUBLIC_KEY, SOMBRA_UPDATER_ENDPOINT and TAURI_SIGNING_PRIVATE_KEY. See UPDATES.md.');
const url=new URL(endpoint);
if(url.protocol!=='https:'||url.username||url.password)throw Error('Release endpoint must use HTTPS without credentials.');
const decoded=Buffer.from(pubkey,'base64').toString('utf8');
if(!decoded.startsWith('untrusted comment:')||Buffer.from(decoded.trim().split('\n').at(-1),'base64').length!==42)throw Error('Use the public .pub key generated by Tauri signer.');
const config=JSON.parse(readFileSync('tauri.conf.json','utf8'));
const pkg=JSON.parse(readFileSync('package.json','utf8'));
const cargo=readFileSync('Cargo.toml','utf8').match(/version = "([^"]+)"/)?.[1];
if(config.version!==pkg.version||config.version!==cargo)throw Error('Align versions in tauri.conf.json, Cargo.toml and package.json.');
const overlay={bundle:{active:true,targets:['nsis'],createUpdaterArtifacts:true,windows:{nsis:{installMode:'currentUser'}}},plugins:{updater:{pubkey,endpoints:[endpoint],windows:{installMode:'passive'}}}};
writeFileSync('tauri.release.local.json',JSON.stringify(overlay,null,2));
const result=spawnSync(process.execPath,['node_modules/@tauri-apps/cli/tauri.js','build','--config','tauri.release.local.json'],{stdio:'inherit',windowsHide:true});
if(result.error)throw result.error;
process.exitCode=result.status??1;
