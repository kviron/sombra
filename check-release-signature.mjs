import {readFileSync} from 'node:fs';
import {createHash,createPublicKey,verify} from 'node:crypto';
import assert from 'node:assert/strict';
const path=process.argv[2];
if(!path)throw new Error('Usage: node check-release-signature.mjs installer.exe');
const config=JSON.parse(readFileSync('tauri.conf.json','utf8'));
const publicLines=Buffer.from(config.plugins.updater.pubkey,'base64').toString('utf8').trim().split(/\r?\n/);
const signatureLines=Buffer.from(readFileSync(path+'.sig','utf8').trim(),'base64').toString('utf8').trim().split(/\r?\n/);
const pub=Buffer.from(publicLines[1],'base64'),signature=Buffer.from(signatureLines[1],'base64');
assert.equal(pub.length,42);assert.equal(signature.length,74);
assert.deepEqual(pub.subarray(2,10),signature.subarray(2,10),'signature key id must match configured updater key');
const key=createPublicKey({key:Buffer.concat([Buffer.from('302a300506032b6570032100','hex'),pub.subarray(10)]),format:'der',type:'spki'});
const algorithm=signature.toString('ascii',0,2);
assert.ok(['ED','Ed'].includes(algorithm));
const data=readFileSync(path),signed=algorithm==='ED'?createHash('blake2b512').update(data).digest():data;
assert.ok(verify(null,signed,key,signature.subarray(10)),'installer signature must verify');
const trusted=signatureLines[2].replace(/^trusted comment: /,'');
assert.ok(verify(null,Buffer.concat([signature.subarray(10),Buffer.from(trusted)]),key,Buffer.from(signatureLines[3],'base64')),'trusted comment signature must verify');
console.log('PASS installer and trusted comment signatures match configured updater public key');
